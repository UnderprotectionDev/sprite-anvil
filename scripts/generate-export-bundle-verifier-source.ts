/**
 * Regenerates `packages/api/src/export-bundle-verifier-source.ts`: the text of
 * the dependency-free verifier that every Export Bundle ships as
 * `verification-kit/verify.ts`. Run it after changing the verifier, then format. Biome ignores the output (biome.json).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const apiSource = join(import.meta.dirname, "..", "packages", "api", "src");
const verifier = readFileSync(
	join(apiSource, "export-bundle-verification.ts"),
	"utf8"
);

writeFileSync(
	join(apiSource, "export-bundle-verifier-source.ts"),
	`/**
 * Generated by scripts/generate-export-bundle-verifier-source.ts from
 * export-bundle-verification.ts. Do not edit by hand; a test fails when it is stale.
 * The verifier's own text, as the Package Verification Kit ships it.
 */
export const exportBundleVerifierSource = ${JSON.stringify(verifier)};
`
);
